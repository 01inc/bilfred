-- Explicit opt-in; no vehicle or installation relationship and no raw IP storage.
CREATE TABLE waitlist_signups (
    id uuid PRIMARY KEY,
    email text NOT NULL UNIQUE CHECK (length(email) BETWEEN 3 AND 254),
    consent_version text NOT NULL,
    consent_text text NOT NULL,
    consented_at timestamptz NOT NULL DEFAULT now(),
    expires_at timestamptz NOT NULL DEFAULT (now() + interval '1 year'),
    source text NOT NULL DEFAULT 'bilfred.com' CHECK (source = 'bilfred.com')
);
CREATE INDEX waitlist_expiry_idx ON waitlist_signups (expires_at);

-- Short-lived counters keyed by an HMAC digest generated by the web server.
CREATE TABLE waitlist_rate_limits (
    bucket text NOT NULL,
    window_start timestamptz NOT NULL,
    requests integer NOT NULL CHECK (requests > 0),
    PRIMARY KEY (bucket, window_start)
);
